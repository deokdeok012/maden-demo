        if (!moved && Math.hypot(dx, dy) < 3) return;
        moved = true;
        s.fpos[id] = { x: p0.x + dx, y: p0.y + dy };
        fig.style.left = `${s.fpos[id].x - L2.box.l}px`;
        fig.style.top = `${s.fpos[id].y - L2.box.t}px`;
        const L22 = layout(g);
        const svg = root.querySelector(".rf-wires");
