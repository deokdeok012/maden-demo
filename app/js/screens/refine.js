      if (e.code === "Space") {
        window.__rfSpace = true;
        document.querySelector("[data-rf-stage]")?.classList.add("grab");
        e.preventDefault();
        return;
      }
      if (letter === "p") {
        s.tool = "prompt";
        draw(g);
      }
      if (!e.altKey && TOOLS.includes(letter)) {
        s.gz = letter;
        s.tool = "select";
        draw(g);
      }
