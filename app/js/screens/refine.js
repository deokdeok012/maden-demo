        canvas.style.transform = `translate(${v.x}px, ${v.y}px) scale(${v.k})`;
        const one = canvas.querySelector(".rf-shot");
        canvas.style.setProperty("--ik", (one && one.getBoundingClientRect().width ? one.offsetWidth / one.getBoundingClientRect().width : 1 / v.k).toFixed(3));
        if (pct) pct.textContent = `${Math.round(v.k * 100)}%`;
