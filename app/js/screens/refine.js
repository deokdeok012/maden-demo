        const r = stage.getBoundingClientRect();
        const v = s.view;
        const nk = Math.max(0.2, Math.min(2.5, v.k * f));
        const px = cx - r.left, py = cy - r.top;
        v.x = px - (px - v.x) * nk / v.k;
        v.y = py - (py - v.y) * nk / v.k;
