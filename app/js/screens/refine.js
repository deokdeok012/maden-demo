  function mount(root, g) {
    const box = root.querySelector(".rf");
    if (!box) return;
    if (!document.querySelector("link[data-rf-fonts]")) document.head.append(el('<link rel="stylesheet" data-rf-fonts href="https://fonts.googleapis.com/css2?family=Baloo+2:wght@700&family=Fredoka:wght@600&family=Lilita+One&family=Luckiest+Guy&family=Noto+Sans+KR:wght@800&display=swap">'));
    bind(box, g);
    root.querySelectorAll("[data-rf-open-play]").forEach((b) => b.addEventListener("click", () => play(g)));
    const keys = (e) => {
      if (!document.querySelector(".rf")) {
        removeEventListener("keydown", keys);
        return;
      }
      if (/^(INPUT|TEXTAREA|SELECT)$/.test(e.target.tagName)) return;
      const s = st(g);
      if ((e.metaKey || e.ctrlKey) && (e.key === "z" || e.key === "Z")) {
        e.preventDefault();
        if (e.shiftKey ? swapHist(s, s.future, s.past) : swapHist(s, s.past, s.future)) draw(g);
        return;
      }
      if ((e.metaKey || e.ctrlKey) && (e.key === "=" || e.key === "+" || e.key === "-")) {
        e.preventDefault();
        s.api?.zoom(e.key === "-" ? 1 / 1.2 : 1.2);
        return;
      }
      if (e.metaKey || e.ctrlKey) return;
      if (e.shiftKey && (e.key === "!" || e.code === "Digit1")) {
        s.api?.fit();
        return;
      }
      if (e.code === "Space") {
        window.__rfSpace = true;
        document.querySelector("[data-rf-stage]")?.classList.add("grab");
        e.preventDefault();
        return;
      }
      if (e.key === "p" || e.key === "P") {
        s.tool = "prompt";
        draw(g);
      }
      if (!e.altKey && TOOLS.includes(e.key.toLowerCase())) {
        s.gz = e.key.toLowerCase();
        s.tool = "select";
        draw(g);
      }
      if (e.key === "Escape" && s.anchorPick) {
        s.anchorPick = false;
        draw(g);
        return;
      }
      if (e.key === "Escape" && (s.ask || s.thread || s.el || s.frame || s.tool === "prompt")) {
        s.ask = null;
        s.thread = null;
        s.el = null;
        s.frame = null;
        s.tool = "select";
        draw(g);
      }
    };
    addEventListener("keydown", keys);
    addEventListener("keyup", (e) => {
      if (e.code === "Space") {
        window.__rfSpace = false;
        document.querySelector("[data-rf-stage]")?.classList.remove("grab");
      }
    });
    const demo = new URLSearchParams(location.hash.split("?")[1] || "").get("demo");
    if (demo === "ask") {
      const s = st(g);
      if (!s.log.length) ask(g, t("rf.c.design"));
    }
  }
  return { render, mount, play };
