      const fit = () => {
        const W = stage.clientWidth, H = stage.clientHeight;
        const cw = canvas.offsetWidth, ch = canvas.offsetHeight;
        const k = Math.max(0.2, Math.min(1, (W - 60) / cw, (H - 100) / ch));
        s.view = { k, x: (W - cw * k) / 2, y: Math.max(16, (H - ch * k) / 2 - 24) };
        apply2();
      };
